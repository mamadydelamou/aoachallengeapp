# PHYSICAL CONSTANTS
# ============================================================================
C               = 299792458.0
CARRIER_FREQ    = 2.61e9
WAVELENGTH      = C / CARRIER_FREQ
ANTENNA_SPACING = 0.07
SUBARRAY_SIZE   = 16
NUM_SOURCES     = 1
N_GRID          = 3600

# ============================================================================
# LOAD DATA
# ============================================================================

@st.cache_data
def load_data():
    data              = np.load('challenge_data.npz', allow_pickle=False)
    channel_matrices  = data['channel_matrices']
    user_positions    = data['user_positions']
    antenna_positions = data['antenna_positions']
    way_indices       = data['way_indices']
    point_indices     = data['point_indices']
    antenna_center    = np.mean(antenna_positions, axis=0)
    cal = {
        'eps_g':        float(data['cal_eps_g'][0]),
        'varsigma_t':   float(data['cal_varsigma_t'][0]),
        'eps_p':        float(data['cal_eps_p'][0]),
        'zeta_SFO_STO': float(data['cal_zeta_SFO_STO'][0]),
        'eta_CPO':      float(data['cal_eta_CPO'][0]),
        'xi_ant':       data['cal_xi_ant'],
    }
    return (channel_matrices, user_positions, antenna_positions,
            antenna_center, way_indices, point_indices, cal)

# ============================================================================
# PIPELINE
# ============================================================================

def compute_ground_truth(ue_position, antenna_center):
    vec  = ue_position - antenna_center
    aoa  = np.degrees(np.arctan2(vec[0], vec[1]))
    dist = np.linalg.norm(vec)
    return aoa, dist


def apply_calibration(channel_matrix, cal):
    n_antennas, n_subcarriers = channel_matrix.shape
    H_cal = channel_matrix.copy().astype(complex)
    for ant in range(n_antennas):
        for sub in range(n_subcarriers):
            zeta_IQ    = np.arctan(
                cal['eps_g'] * np.sin(sub * cal['varsigma_t'] + cal['eps_p'])
                / (np.cos(sub * cal['varsigma_t']) + 1e-10)
            )
            phase_corr = (zeta_IQ + sub * cal['zeta_SFO_STO']
                          + cal['eta_CPO'] + cal['xi_ant'][ant])
            H_cal[ant, sub] *= np.exp(-1j * phase_corr)
    return H_cal


def compute_music(channel_matrix, n_grid=N_GRID):
    n_antennas, n_subcarriers = channel_matrix.shape
    n_subarrays = n_antennas - SUBARRAY_SIZE + 1
    R_smooth    = np.zeros((SUBARRAY_SIZE, SUBARRAY_SIZE), dtype=complex)
    J = np.eye(SUBARRAY_SIZE)[::-1]
    for i in range(n_subarrays):
        H_sub    = channel_matrix[i:i+SUBARRAY_SIZE, :]
        R_sub    = H_sub @ H_sub.conj().T / n_subcarriers
        R_smooth += R_sub + J @ R_sub.conj() @ J
    R_smooth /= (2 * n_subarrays)

    eigenvalues, eigenvectors = np.linalg.eig(R_smooth)
    idx          = eigenvalues.argsort()[::-1]
    eigenvectors = eigenvectors[:, idx]
    En           = eigenvectors[:, NUM_SOURCES:]

    angles_deg = np.linspace(-90, 90, n_grid)
    spectrum   = np.zeros(n_grid)
    for i, theta in enumerate(angles_deg):
        sin_t = np.sin(np.radians(theta))
        a     = np.exp(-1j * 2*np.pi * ANTENNA_SPACING / WAVELENGTH
                       * sin_t * np.arange(SUBARRAY_SIZE)).reshape(-1, 1)
        proj  = En.conj().T @ a
        spectrum[i] = 1.0 / (np.abs(proj.conj().T @ proj).item() + 1e-12)

    peak_idx = np.argmax(spectrum)
    return angles_deg[peak_idx], spectrum, angles_deg


def build_steering_channel(theta_hat_deg, n_antennas, n_subcarriers):
    sin_t    = np.sin(np.radians(theta_hat_deg))
    steering = np.exp(-1j * 2*np.pi * ANTENNA_SPACING / WAVELENGTH
                      * sin_t * np.arange(n_antennas))
    return np.outer(steering, np.ones(n_subcarriers))

# ============================================================================
# COMPUTE PROFILE
# ============================================================================

@st.cache_data
def compute_profile(_channel_matrices, _user_positions, _antenna_center, _cal):
    profile = []
    for H_raw, pos in zip(_channel_matrices, _user_positions):
        gt_aoa, dist        = compute_ground_truth(pos, _antenna_center)
        H_cal               = apply_calibration(H_raw, _cal)
        est_aoa, spec, angs = compute_music(H_cal)
        profile.append({
            'gt_aoa':  gt_aoa,
            'est_aoa': est_aoa,
            'error':   abs(est_aoa - gt_aoa),
            'dist':    dist,
            'spec':    spec,
            'angles':  angs,
        })
    margin = np.max([p['error'] for p in profile])
    for p in profile:
        p['margin']      = margin
        p['interval_lo'] = p['gt_aoa'] - margin
        p['interval_hi'] = p['gt_aoa'] + margin
    return profile, margin

