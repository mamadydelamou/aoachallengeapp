def main():

    # ---- Load ---------------------------------------------------------------
    try:
        (channel_matrices, user_positions, antenna_positions,
         antenna_center, way_indices, point_indices, cal) = load_data()
    except FileNotFoundError:
        st.error("`challenge_data.npz` not found — run `extract_challenge_data.py` first.")
        st.stop()
    except KeyError as e:
        st.error(f"Missing key in npz: {e}. Re-run `extract_challenge_data.py`.")
        st.stop()

    n_ant, n_sub = channel_matrices[0].shape

    with st.spinner("Computing MUSIC on 26 legitimate points…"):
        profile, margin = compute_profile(
            channel_matrices, user_positions, antenna_center, cal
        )

    # =========================================================================
    # HERO HEADER
    # =========================================================================
 
    st.markdown(f"""
    <div class="hero">
        <div class="hero-tag">Robust-6G · Security Challenge</div>
        <div class="hero-title">AoA Impersonation Challenge</div>
        <div class="hero-sub">
            This challenge demonstrates <strong style="color:#7dd3fc">Proposition 1</strong> of the work proposed in 
            <a href="https://arxiv.org/pdf/2503.11508.pdf"> Here</a>.
            An adversary at angle θ̂  cannot impersonate a legitimate transmitter at angle θ, regardless of any complex 
            precoding, as long as θ̂ ≠ θ.
        </div>
    </div>
    """, unsafe_allow_html=True)

    # =========================================================================
    # SECTION 1 — Subsampling of the original dataset
    # =========================================================================
    st.markdown('<div class="section-card">', unsafe_allow_html=True)
    st.markdown('<div class="section-title">Subset of the Original Dataset</div>',
                unsafe_allow_html=True)
    st.markdown(f""" 
    <p style="font-size:20px; line-height:1.8; color:#cbd5e1; text-align: justify;">
    In this challenge, we consider a subset of 26 data points extracted from a chunk of the original dataset corresponding,
    which comprises 251 ways and 251 points per way. The subsampling is performed by retaining a single point per way, selecting every 
    10th way (w0, w10, w20, ..., w250), and always picking the point located at the farthest distance from the antenna array.
    This last criterion follows from the snake structure of the measurement grid: the farthest point alternates between index 250 for
    even-numbered ways and index 0 for odd-numbered ways. The resulting 26 points are physically separated by 50~mm from one another,
    all lying along the same far. This selection is motivated by two properties: first, the uniform spatial separation ensures that the 
    26 reference AoA values are well-spread and geometrically distinct, eliminating any angular ambiguity in the authentication process; 
    second, operating at maximum distance from the array places all points in a consistent far-field regime, where AoA estimation via MUSIC 
    is most accurate and reliable. The figure below illustrates the selection process.
    </p>
    """, unsafe_allow_html=True)
    # ── dataset structure (matplotlib) ────────────────────────────────────
    st.pyplot(draw_dataset_structure(), use_container_width=True)
    plt.close()

    st.markdown(f""" 
    <p style="font-size:20px; line-height:1.8; color:#cbd5e1; text-align: justify;">
    The system model is illustrated in the figure below. The reference coordinate system is centered at the midpoint of the ULA, which comprises 
    64 antenna elements arranged with 0.87 half-wavelength inter-element spacing at a carrier frequency of 2.61~GHz and 100 subcarriers. The 26 selected reference points
    are positioned along the far line. All reference positions lie to the left of the array center,resulting in strictly negative ground-truth AoA 
    values. 
    For each reference point, the AoA θ is defined as the angle between the incoming wavefront and the broadside 
    direction of the array, and is estimated at the base station receiver using the MUSIC algorithm. 
    </p>
    """, unsafe_allow_html=True) 
    st.latex(r"\mathbf{H} \in \mathbb{C}^{64 \times 100}")



    # ── System model diagram (matplotlib) ────────────────────────────────────
    st.pyplot(draw_system_model(), use_container_width=True)
    plt.close()

    st.divider()

    # =========================================================================
    # SECTION 2 — PROFILE
    # =========================================================================
    st.markdown('<div class="section-card">', unsafe_allow_html=True)
    st.markdown('<div class="section-title">Legitimate Profile</div>',
                unsafe_allow_html=True)
    st.markdown(f"""
    <p style="font-size:20px; line-height:1.8; color:#cbd5e1; text-align: justify;">
    The AoAs are estimated as follows:<br>
    - We first compute the ground-truth AoA (GT) of each datapoint using the given ground-truth cordinates.<br>
    - Knowing that original collected data is not pure due to hardware impairments, we calibrated the datapoints for
    impairments mitigation.<br>
    - After calibration, we estimatte AoAs using MUSIC (θ) and using the GT AoAs as reference, we compute the estimation
    error for each datapoint. Finally, the maximum error is used as the acceptance interval to garanty that any AoA estimate 
    stays within the interval. The maximum error here is E = ±{margin:.4f}°. <br>
    - Finally, Proposition 1 can be rewritten as follows: An adversary at angle θ̂  cannot impersonate a legitimate transmitter at angle θ, regardless of any complex 
    precoding, as long as θ̂  ∉ I = [GT. + E, MUSIC est. - E].<br>
    The datapoints are fully public, the attacker knows all of them in the table below. The table contains the selected way, the point index, 
    the ground-truth AoA (°), the MUSIC estimated AoA (°), the error (°), the low and high bounds of the acceptance interval (°).
    </p>
    """, unsafe_allow_html=True)

    rows = []
    for p, w, pt in zip(profile, way_indices, point_indices):
        rows.append({
            "Way":             int(w),
            "Point":           int(pt),
            "GT AoA (°)":      round(p['gt_aoa'],       4),
            "MUSIC est. (°)":  round(p['est_aoa'],      4),
            "Error (°)":       round(p['error'],        4),
            "Interval lo (°)": round(p['interval_lo'],  4),
            "Interval hi (°)": round(p['interval_hi'],  4),
        })
    st.dataframe(pd.DataFrame(rows), use_container_width=True, hide_index=True)

    # ── Estimated AoA and acceptance interval plot ────────────────────────────────────
    st.markdown(f"""
    <p style="font-size:20px; line-height:1.8; color:#cbd5e1; text-align: justify;">
    The figure below illustrates the the ground-truth, the estimated AoAs (MUSIC) of each datapoint, along with the acceptance interval ±{margin:.4f}°.
    </p>
    """, unsafe_allow_html=True)
    fig, ax = plt.subplots(figsize=(13, 4))
    fig.patch.set_facecolor("#0d1b2e")
    ax.set_facecolor("#0d1b2e")
    x   = np.arange(len(profile))
    gt  = [p['gt_aoa']      for p in profile]
    est = [p['est_aoa']     for p in profile]
    lo  = [p['interval_lo'] for p in profile]
    hi  = [p['interval_hi'] for p in profile]

    ax.plot(x, gt,  'o-',  color='#38bdf8', lw=2,   ms=7, label='Ground Truth')
    ax.plot(x, est, 's--', color='#fb923c', lw=1.5, ms=6, label='MUSIC estimate')
    ax.fill_between(x, lo, hi, alpha=0.25, color='#22c55e',
                    label=f'Acceptance interval ±{margin:.4f}°')
    ax.set_xticks(x)
    ax.set_xticklabels([f"w{w}" for w in way_indices], rotation=45,
                       fontsize=9, color="#94a3b8")
    ax.set_ylabel("AoA (°)", fontsize=12, color="#94a3b8")
    ax.set_title("26 far-points - Ground Truth vs MUSIC + acceptance intervals",
                 fontsize=13, color="#e2e8f0")
    ax.tick_params(colors="#94a3b8", labelsize=10)
    for spine in ax.spines.values():
        spine.set_edgecolor("#334155")
    ax.legend(fontsize=10, facecolor="#1e3a5f",
              labelcolor="#e2e8f0", edgecolor="#334155")
    ax.grid(alpha=0.15, color="#334155")
    st.pyplot(fig)
    plt.close()
    st.markdown('</div>', unsafe_allow_html=True)

    st.divider()

    # =========================================================================
    # SECTION 2 — ATTACK
    # =========================================================================
    st.markdown('<div class="section-card">', unsafe_allow_html=True)
    st.markdown('<div class="section-title">2 · Attack — Try to Impersonate a Target Point</div>',
                unsafe_allow_html=True)
    st.markdown("""
    <p style="font-size:20px; line-height:1.8; color:#cbd5e1; text-align: justify;">
    Select any datapoint. You know its ground-truth AoA and acceptance interval I. Choose your physical angle θ̂  ∉ I and any complex 
    precoding scalar q (a complex scalar will be represented by its modulus |q|, and phase). The MUSIC estimator will output your true angle.  
    Can you make it output an angle in the acceptance interval I?
    </p>
    """, unsafe_allow_html=True)

    target_labels = [
        f"way {w}  |  GT = {p['gt_aoa']:.4f}°  -->  "
        f"[{p['interval_lo']:.4f}°,  {p['interval_hi']:.4f}°]"
        for p, w in zip(profile, way_indices)
    ]
    target_idx = st.selectbox(
        "Choose the target point to impersonate",
        range(len(profile)),
        format_func=lambda i: target_labels[i]
    )
    target = profile[target_idx]

    st.info(
        f"**Target:** way {int(way_indices[target_idx])}  |  "
        f"GT AoA = **{target['gt_aoa']:.4f}°**  |  "
        f"Acceptance interval = **[{target['interval_lo']:.4f}°,  "
        f"{target['interval_hi']:.4f}°]**  |  "
        f"Width = {target['interval_hi'] - target['interval_lo']:.4f}°"
    )

    st.markdown("---")
    st.markdown("""
    <p style="font-size:20px; color:#e2e8f0; font-weight:600;">
    Angle + Precoding - Proposition 1 attacker model
    </p>
    """, unsafe_allow_html=True)
    st.markdown("""
    <p style="font-size:20px; line-height:1.8; color:#cbd5e1; text-align: justify;">
    You are physically at angle θ̂ and apply a complex scalar q to your 
    transmitted signal. Your channel seen by the receiver is:  
    H_attack = q · a(θ̂)  
    where a(θ̂) is the steering vector at your true angle.  
    The theory proves MUSIC will always output θ̂ regardless of q.
    </p>
    """, unsafe_allow_html=True)

    # ---- Annotated slider bar -----------------------------------------------
    st.markdown(""" <p style="font-size:20px; color:#e2e8f0; font-weight:600;"> Choose your attack angle θ̂:</p>""", unsafe_allow_html=True)
    angle_slider_with_highlight(target['interval_lo'], target['interval_hi'],
                                key="theta_hat")
    theta_hat = st.session_state.get("theta_hat", None)
    if theta_hat is None:
        st.info("Please enter an angle above to continue.")
        st.stop()

    # Warning if inside interval
    inside = target['interval_lo'] <= theta_hat <= target['interval_hi']
    if inside:
        st.markdown(
            f'<div class="interval-warning">'
            f'<strong>Your angle θ̂ = {theta_hat:.2f}° is inside the acceptance '
            f'interval [{target["interval_lo"]:.4f}°, {target["interval_hi"]:.4f}°].</strong><br>'
            f'If you pass with this angle, it is <strong>not a real spoof</strong> — '
            f'you are simply at the legitimate user\'s location. '
            f'A genuine impersonation attack requires θ̂ to be <strong>outside</strong> '
            f'the interval. Try to pass from outside!'
            f'</div>',
            unsafe_allow_html=True
        )

    # Precoding sliders
    col1, col2 = st.columns(2)
    with col1:
        q_amp = st.number_input(
            "Precoding amplitude |q|",
            value=None,
            step=0.01,
            format="%.2f",
            placeholder="Enter any positive amplitude",
            help="Amplitude of your precoding scalar q."
        )
    with col2:
        q_phase = st.number_input(
            "Precoding phase ∠q (°)",
            min_value=-180.0,
            max_value=180.0,
            value=None,
            step=1.0,
            format="%.1f",
            placeholder="Enter phase between -180° and 180°",
            help="Phase of your precoding scalar q."
        )

    if q_amp is None or q_phase is None:
        st.info("Please enter both amplitude and phase of your precoder to continue.")
        st.stop()
    if q_amp <= 0:
        st.error("Amplitude |q| must be strictly positive.")
        st.stop()

    q        = q_amp * np.exp(1j * np.radians(q_phase))
    H_attack = q * build_steering_channel(theta_hat, n_ant, n_sub)
    st.markdown(
        f"**Submitted:** `H = q · a(θ̂)`  with  "
        f"|q| = {q_amp:.2f},  ∠q = {q_phase:.0f}°,  θ̂ = {theta_hat:.1f}°"
    )
    if st.button("Submit attack", type="primary"):
        run_and_display_attack(H_attack, cal, target, theta_hat)
    st.markdown('</div>', unsafe_allow_html=True)
    st.divider()

    # =========================================================================
    # SECTION 3 — THEORY
    # =========================================================================
    st.divider()
    st.markdown('<div class="section-card">', unsafe_allow_html=True)
    st.markdown('<div class="section-title">Theoretical background - Proposition 1</div>',
                unsafe_allow_html=True)
    st.markdown('<p style="font-size:22px; font-weight:600; color:#e2e8f0;">Why precoding cannot change your AoA</p>',
                unsafe_allow_html=True)
    st.markdown('<p style="font-size:20px; line-height:1.8; color:#cbd5e1;">The signal received from the <strong>legitimate transmitter</strong> at angle θ is:</p>',
                unsafe_allow_html=True)
    st.latex(r"x = a(\theta)\, s_{0} + n")
    st.markdown('<p style="font-size:20px; line-height:1.8; color:#cbd5e1;">where the steering vector is:</p>',
                unsafe_allow_html=True)
    st.latex(
        r"a(\theta) = \bigl[1,\; e^{-j\kappa\sin\theta},\; \ldots,\; "
        r"e^{-j\kappa(M-1)\sin\theta}\bigr]^T, \quad "
        r"\kappa = \frac{2\pi d}{\lambda}"
    )
    st.markdown('<p style="font-size:20px; line-height:1.8; color:#cbd5e1;">An <strong>adversary</strong> at angle θ̂ applies a complex precoding scalar <strong>q</strong>:</p>',
                unsafe_allow_html=True)
    st.latex(r"\hat{x} = \hat{a}(\hat{\theta})\, q\, s_0 + \hat{n}")
    st.markdown('<p style="font-size:20px; line-height:1.8; color:#cbd5e1;">The spatial covariance matrix seen by the receiver becomes:</p>',
                unsafe_allow_html=True)
    st.latex(
        r"R = |q|^2\sigma_s^2\;\hat{a}(\hat{\theta})\hat{a}(\hat{\theta})^H "
        r"+ \sigma_n^2 I"
    )
    st.markdown(
        '<p style="font-size:20px; line-height:1.8; color:#cbd5e1; text-align:justify;">'
        '<strong>Key insight:</strong> The scalar <strong>q</strong> does <strong>not</strong> '
        'change the steering vector â(θ̂). MUSIC finds the angle whose steering vector is '
        '<strong>orthogonal to the noise subspace</strong>, this is determined entirely '
        'by <strong>θ̂</strong>, not by <strong>q</strong>. MUSIC always outputs θ̂  regardless of q.'
        '</p>',
        unsafe_allow_html=True
    )
  
    st.markdown('</div>', unsafe_allow_html=True)
 
 
if __name__ == "__main__":
    main()
 